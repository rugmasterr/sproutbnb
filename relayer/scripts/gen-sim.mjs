// Regenerates src/simBytecode.ts from sim/out (run `forge build` in relayer/sim first).
// Usage: node scripts/gen-sim.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const art = JSON.parse(readFileSync(resolve(root, 'sim/out/SimAccount.sol/SimAccount.json'), 'utf8'))
const code = art.deployedBytecode.object
if (!/^0x[0-9a-f]+$/.test(code)) throw new Error('bad bytecode')
writeFileSync(
  resolve(root, 'src/simBytecode.ts'),
  `// GENERATED by scripts/gen-sim.mjs from sim/SimAccount.sol (solc 0.8.26, optimizer 200, cancun). Do not edit.\n` +
    `// Runtime code placed at the account address via eth_estimateGas state override for /quote-gas only.\n` +
    `export const SIM_ACCOUNT_RUNTIME = '${code}' as const\n`,
)
console.log('wrote src/simBytecode.ts', (code.length - 2) / 2, 'bytes')
